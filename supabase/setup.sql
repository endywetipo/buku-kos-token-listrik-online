  to authenticated
  using (exists (select 1 from public.admin_emails a where lower(a.email) = lower(auth.jwt() ->> 'email')))
  with check (exists (select 1 from public.admin_emails a where lower(a.email) = lower(auth.jwt() ->> 'email')));
drop policy if exists "admin delete token_entries" on public.token_entries;
create policy "admin delete token_entries" on public.token_entries for delete
  to authenticated
  using (exists (select 1 from public.admin_emails a where lower(a.email) = lower(auth.jwt() ->> 'email')));
drop policy if exists "owner update token_entries" on public.token_entries;
create policy "owner update token_entries" on public.token_entries for update
