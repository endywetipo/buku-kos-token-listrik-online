-- ===== kos table =====
CREATE TABLE IF NOT EXISTS public.kos (
  id bigint generated by default as identity primary key,
  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  nama_kos text NOT NULL,
  kota text,
  kode_undangan text UNIQUE NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.kos ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT ON public.kos TO authenticated;

DROP POLICY IF EXISTS "authenticated read kos" ON public.kos;
CREATE POLICY "authenticated read kos" ON public.kos FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated insert kos" ON public.kos;
CREATE POLICY "authenticated insert kos" ON public.kos FOR INSERT
  TO authenticated WITH CHECK (true);

-- ===== profiles table =====
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text,
  whatsapp text,
  role text DEFAULT 'tenant',
  kos_id bigint REFERENCES public.kos(id) ON DELETE SET NULL,
  kamar integer,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON public.profiles TO authenticated;

DROP POLICY IF EXISTS "authenticated read profiles" ON public.profiles;
CREATE POLICY "authenticated read profiles" ON public.profiles FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated insert own profile" ON public.profiles;
CREATE POLICY "authenticated insert own profile" ON public.profiles FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "authenticated update own profile" ON public.profiles;
CREATE POLICY "authenticated update own profile" ON public.profiles FOR UPDATE
  TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

-- ===== kos_entries table =====
CREATE TABLE IF NOT EXISTS public.kos_entries (
  id bigint generated by default as identity primary key,
  kamar integer NOT NULL,
  nama text NOT NULL,
  bulan text NOT NULL,
  jumlah integer NOT NULL DEFAULT 300000,
  tanggal date NOT NULL DEFAULT current_date,
  periode text NOT NULL,
  user_id uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  kos_id bigint REFERENCES public.kos(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'lunas',
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.kos_entries ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.kos_entries TO authenticated;

DROP POLICY IF EXISTS "authenticated read kos_entries" ON public.kos_entries;
CREATE POLICY "authenticated read kos_entries" ON public.kos_entries FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated insert kos_entries" ON public.kos_entries;
CREATE POLICY "authenticated insert kos_entries" ON public.kos_entries FOR INSERT
  TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "admin update kos_entries" ON public.kos_entries;
CREATE POLICY "admin update kos_entries" ON public.kos_entries FOR UPDATE
  TO authenticated
  USING (exists (select 1 from public.admin_emails a where lower(a.email) = lower(auth.jwt() ->> 'email')))
  WITH CHECK (exists (select 1 from public.admin_emails a where lower(a.email) = lower(auth.jwt() ->> 'email')));

DROP POLICY IF EXISTS "admin delete kos_entries" ON public.kos_entries;
CREATE POLICY "admin delete kos_entries" ON public.kos_entries FOR DELETE
  TO authenticated
  USING (exists (select 1 from public.admin_emails a where lower(a.email) = lower(auth.jwt() ->> 'email')));

DROP POLICY IF EXISTS "owner update kos_entries" ON public.kos_entries;
CREATE POLICY "owner update kos_entries" ON public.kos_entries FOR UPDATE
  TO authenticated
  USING (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner' and p.kos_id = kos_entries.kos_id))
  WITH CHECK (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner' and p.kos_id = kos_entries.kos_id));

DROP POLICY IF EXISTS "owner delete kos_entries" ON public.kos_entries;
CREATE POLICY "owner delete kos_entries" ON public.kos_entries FOR DELETE
  TO authenticated
  USING (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'owner' and p.kos_id = kos_entries.kos_id));

