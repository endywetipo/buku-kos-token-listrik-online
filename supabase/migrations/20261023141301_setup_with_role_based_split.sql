/*
# Setup database with role-based access and auto-split token support

## Overview
Creates the core tables for BukuKosOnline: admin_emails, kos, profiles, kos_entries,
token_entries. Adds user_id, kos_id, and status columns to support role-based
dashboards and the "Beli Token Bersama" auto-split feature.

## New Tables
1. admin_emails — whitelist of admin email addresses (created first, referenced by policies)
2. kos — kos building entity with owner_id, invite code
3. profiles — user profile with role (owner/tenant), kos_id, kamar
4. kos_entries — kos payment records with user_id, kos_id, status
5. token_entries — token listrik records with user_id, kos_id, status

## Security
- RLS enabled on all tables.
- All authenticated users can read kos/token entries (app filters by role client-side).
- Authenticated can insert entries.
- Admins (via admin_emails) and owners (via profiles kos_id match) can update/delete.
- Tenants can update their own token_entries (to mark status as paid).

## Important Notes
1. user_id defaults to auth.uid() so inserts work even when client omits it.
2. status defaults to 'lunas' for backward compat. Auto-split sets 'belum_lunas'.
3. kos_id is nullable for backward compat.
*/

-- ===== admin_emails table (must exist before other policies reference it) =====
CREATE TABLE IF NOT EXISTS public.admin_emails (
  email text PRIMARY KEY
);
ALTER TABLE public.admin_emails ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.admin_emails TO authenticated;

DROP POLICY IF EXISTS "admin read own email" ON public.admin_emails;
CREATE POLICY "admin read own email" ON public.admin_emails FOR SELECT
  TO authenticated
  USING (lower(email) = lower(auth.jwt() ->> 'email'));

